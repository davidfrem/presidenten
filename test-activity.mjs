import assert from "node:assert/strict";
import { createActivityStore, isAdmin } from "./player-activity.js";
let time = Date.UTC(2026, 8, 15);
const store = createActivityStore({ now: () => time });
await store.touch("one", { name: "David", mode: "solo" });
assert.equal((await store.active()).length, 1);
time += 121000;
assert.equal((await store.active()).length, 0);
await store.touch("one", { name: "David", mode: "solo" });
await store.touch("one", { name: "David", mode: "solo" }, true);
assert.equal((await store.active()).length, 0);
const history = await store.list(time - 86400000, time + 1);
assert.equal(history.items[0].name, "David");
assert.ok(history.items[0].endedAt);
await Promise.all([store.touch("two", { name: "Lisa" }), store.touch("two", { name: "Lisa" }, true)]);
assert.equal((await store.active()).length, 0);
for (let i = 0; i < 205; i++) await store.touch(`p${String(i).padStart(3, "0")}`, { name: "Test" });
const first = await store.list(time - 86400000, time + 1);
assert.equal(first.items.length, 200);
assert.ok(first.cursor);
const second = await store.list(time - 86400000, time + 1, first.cursor);
assert.equal(second.items.length, 7);
assert.equal(new Set([...first.items, ...second.items].map((row) => row.id)).size, 207);
assert.equal((await store.totals(time - 86400000, time + 1))[0].sessions, 207);
assert.equal(isAdmin({ email: "owner@gmail.com", email_verified: true }, "owner@gmail.com"), true);
assert.equal(isAdmin({ email: "owner@gmail.com", email_verified: false }, "owner@gmail.com"), false);
assert.equal(isAdmin({ email: "other@gmail.com", email_verified: true }, "owner@gmail.com"), false);
time += 91 * 86400000;
await store.touch("new", { name: "New" });
assert.equal((await store.list(0, time + 1)).items.length, 1);
console.log("Activity tests passed.");
